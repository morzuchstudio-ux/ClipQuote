test('mobile edit supports changing video and keeps controls inside the dialog',async({page,accountState})=>{
  accountState.clips=[{id,owner_id:userId,data:{...original}}];
  await page.setViewportSize({width:390,height:844});
  await openEditor(page);
  await page.getByRole('button',{name:'Change link',exact:true}).click();
  await expect(page.getByLabel('YouTube link')).toHaveValue(`https://www.youtube.com/watch?v=${original.videoId}`);
  await page.getByLabel('YouTube link').fill('https://youtu.be/dQw4w9WgXcQ');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await expect(page.getByLabel('Start',{exact:true})).toHaveValue('');
  await page.getByLabel('Start',{exact:true}).fill('5.1');
  await page.getByLabel('End',{exact:true}).fill('8.6');
  await expect(page.getByRole('button',{name:'Play video',exact:true})).toBeEnabled();
  expect(await page.evaluate(()=>window.testPlayer.state)).not.toBe(1);
  const dialog=page.getByRole('dialog',{name:'Edit clip'});
  expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
  await page.getByRole('button',{name:'Save changes',exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:'/tmp/clipquote-edit-mobile.png'});
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  expect(accountState.clips[0].data).toMatchObject({id,videoId:'dQw4w9WgXcQ',start:5.1,end:8.6});
});
